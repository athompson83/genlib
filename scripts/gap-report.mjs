#!/usr/bin/env node
// Content gaps, measured (after SkillFoundry's "find the missing capability first" loop): runs each common app
// task in tests/fixtures/gap-tasks.json through quick and classifies the answer.
//   own       the best match is Genlib's own tested code (capability, module, integration, recipe, template)
//   external  only external records (libraries, services, indexes) answer it: a candidate for a Genlib package
//   none      quick answers no-match: nothing fits yet
// Writes docs/gaps.md (with --write) or prints JSON. Offline and deterministic.
import { readFileSync, writeFileSync } from 'node:fs';
import { findInSources, loadSources } from '../lib/discover.mjs';
import { quickPick } from '../lib/brief.mjs';

const OWN = new Set(['capability', 'module', 'integration', 'recipe', 'language-example', 'template']);
const { tasks } = JSON.parse(readFileSync(new URL('../tests/fixtures/gap-tasks.json', import.meta.url), 'utf8'));
const sources = await loadSources();
const rows = tasks.map(task => {
  const found = findInSources(sources, task, { limit: 4 });
  const pick = quickPick(found);
  const ownHit = found.results.find(result => OWN.has(result.type));
  const status = pick.best === null ? 'none' : OWN.has(pick.best.split(':')[0]) ? 'own' : ownHit ? 'own' : 'external';
  return { task, status, best: pick.best ?? null, own: ownHit ? `${ownHit.type}:${ownHit.id}` : null };
});
const count = status => rows.filter(row => row.status === status).length;
const summary = { tasks: rows.length, own: count('own'), external: count('external'), none: count('none') };
if (process.argv.includes('--write')) {
  const table = status => rows.filter(row => row.status === status).map(row => `| ${row.task} | ${row.best ? '`' + row.best + '`' : '-'} |`).join('\n');
  writeFileSync(new URL('../docs/gaps.md', import.meta.url), `# Content gaps

Generated by \`node scripts/gap-report.mjs --write\` from \`tests/fixtures/gap-tasks.json\` (${summary.tasks} common application tasks). It shows which tasks Genlib answers with its own tested code and which still need a package. The probe is offline and lexical: it measures what \`quick\` returns, not whether the code fits a particular app.

| Answered by | Tasks |
| --- | ---: |
| Genlib's own code (capability, module, integration pack, recipe, template) | ${summary.own} |
| External records only (a library, service or index entry) | ${summary.external} |
| Nothing (quick says no match) | ${summary.none} |

## Build next: external only

These tasks have no Genlib package yet. Each is a candidate for a feature package with a contract, tests and evidence, built like \`org-invitations\`. Wrap the best external project, or write original code, depending on scope and license.

| Task | Current best answer |
| --- | --- |
${table('external')}

## Not covered at all

| Task | |
| --- | --- |
${table('none')}

## Covered by Genlib code

| Task | Best answer |
| --- | --- |
${table('own')}
`);
  console.log(JSON.stringify(summary));
} else process.stdout.write(JSON.stringify({ summary, rows }, null, 2) + '\n');
