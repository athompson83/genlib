#!/usr/bin/env node
// Content gaps, measured (after SkillFoundry's "find the missing capability first" loop): runs each common app
// task in tests/fixtures/gap-tasks.json through quick and classifies the answer.
//   coverage  full / partial / unverified / none from the task's feature contract (requirement-level evidence)
//   routing   what quick returns for the phrase (own / external / none); lexical, kept separate from coverage
// Writes docs/gaps.md (with --write) or prints JSON. Offline and deterministic.
import { readFileSync, writeFileSync } from 'node:fs';
import { findInSources, loadSources } from '../lib/discover.mjs';
import { quickPick } from '../lib/brief.mjs';
import { contractCoverage, loadContracts } from '../lib/coverage.mjs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

const OWN = new Set(['capability', 'module', 'integration', 'recipe', 'language-example', 'template']);
const { tasks } = JSON.parse(readFileSync(new URL('../tests/fixtures/gap-tasks.json', import.meta.url), 'utf8'));
const sources = await loadSources();
const contracts = loadContracts(root);
const rows = tasks.map(task => {
  const found = findInSources(sources, task, { limit: 4 });
  const pick = quickPick(found);
  const routed = pick.best === null ? 'none' : OWN.has(pick.best.split(':')[0]) ? 'own' : 'external';
  const contract = contracts.find(item => item.tasks.includes(task));
  const coverage = contract ? contractCoverage(contract) : null;
  return { task, contract: contract?.id ?? null, level: coverage?.level ?? 'no-contract', verified: coverage?.verified ?? null, missing: coverage?.missing ?? [], routed, best: pick.best ?? null };
});
const count = (key, value) => rows.filter(row => row[key] === value).length;
const summary = {
  tasks: rows.length,
  coverage: { full: count('level', 'full'), partial: count('level', 'partial'), unverified: count('level', 'unverified'), none: count('level', 'none'), noContract: count('level', 'no-contract') },
  routing: { own: count('routed', 'own'), external: count('routed', 'external'), none: count('routed', 'none') },
};
if (process.argv.includes('--write')) {
  const table = level => rows.filter(row => row.level === level).map(row =>
    `| ${row.task} | \`${row.contract ?? '-'}\` | ${row.verified ?? '-'} | ${row.missing.length ? row.missing.join(', ') : '-'} | ${row.best ? '`' + row.best + '`' : '-'} |`).join('\n');
  const head = '| Task | Contract | Verified | Not verified by Genlib | Search returns |\n| --- | --- | ---: | --- | --- |';
  const section = (title, level, intro) => rows.some(row => row.level === level) ? `## ${title}\n\n${intro}\n\n${head}\n${table(level)}\n\n` : '';
  writeFileSync(new URL('../docs/gaps.md', import.meta.url), `# Feature coverage and gaps

Generated by \`node scripts/gap-report.mjs --write\` from \`tests/fixtures/gap-tasks.json\` (${summary.tasks} common application tasks) and the feature contracts in \`resources/feature-contracts/\`. Run \`genlib coverage <task>\` for one feature.

Coverage is credited per requirement, never per search hit. Each contract lists what the feature needs in a real multi-tenant app, and an implementation counts for a requirement only when a named repository test exercises it (\`fixture-verified\`). Lower statuses (\`install-supported\`, \`plan-available\`, \`cataloged\`) are shown but not counted as covered. The receiving application raises a requirement to \`application-verified\` with \`genlib adopted <module> --test "<cmd>" --accepts <contract>#<requirement>\`.

| Coverage | Tasks |
| --- | ---: |
| Full: every requirement fixture-verified | ${summary.coverage.full} |
| Partial: some requirements fixture-verified | ${summary.coverage.partial} |
| Unverified: only install, plan or catalog claims | ${summary.coverage.unverified} |
| None: no implementation claims a requirement | ${summary.coverage.none} |${summary.coverage.noContract ? `\n| No contract written yet | ${summary.coverage.noContract} |` : ''}

The "Search returns" column is what \`quick\` picks for the task phrase (lexical routing): ${summary.routing.own} tasks route to Genlib code and ${summary.routing.external} to external records. Routing to Genlib code does not mean the feature is covered; compare it with the Verified column.

${section('Partial: build next', 'partial', 'Genlib verifies some requirements. The listed ones are the remaining work, for the app or for a new package.')}${section('Unverified', 'unverified', 'Something claims these requirements, but no repository test exercises them yet.')}${section('Not covered', 'none', 'No implementation claims any requirement. Candidates for new feature packages.')}${section('No contract yet', 'no-contract', 'Write a contract in resources/feature-contracts/ before counting these.')}${section('Full', 'full', 'Every requirement is exercised by a named repository test. The app still verifies its own integration.')}`);
  console.log(JSON.stringify(summary));
} else process.stdout.write(JSON.stringify({ summary, rows }, null, 2) + '\n');
