#!/usr/bin/env node
// Measures what an agent actually reads on Genlib's main paths and writes docs/token-budget.md.
// Every number comes from running the real command against this checkout; tokens are estimated
// at 4 bytes per token and labelled as an estimate. --check fails when the committed report is stale.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const FILE = 'docs/token-budget.md';
const cli = (...args) => execFileSync(process.execPath, [root + 'bin/genlib.mjs', ...args], { cwd: root, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024, env: { ...process.env, GENLIB_ROOT: '$GENLIB_ROOT' } });
const mcp = request => execFileSync(process.execPath, [root + 'bin/genlib-mcp.mjs'], { cwd: root, env: { ...process.env, GENLIB_ROOT: '$GENLIB_ROOT' }, input: JSON.stringify({ jsonrpc: '2.0', id: 1, ...request }) + '\n', encoding: 'utf8' });
const bytes = text => Buffer.byteLength(text);

export function measure() {
  const rows = [];
  const add = (path, command, genlib, baselineLabel, baseline) => rows.push({ path, command, genlib, baselineLabel, baseline });
  for (const task of [['verify', 'stripe', 'webhook'], ['passkey', 'login', '--language', 'go'], ['csv', 'export', '--language', 'python']]) {
    const words = task.join(' ');
    const full = bytes(cli('find', ...task, '--json'));
    add('Pick code for a task', `quick ${words}`, bytes(cli('quick', ...task)), 'find --json (8 full records)', full);
    add('Compare options', `find ${words}`, bytes(cli('find', ...task)), 'find --json (8 full records)', full);
  }
  for (const [ref, language] of [['totp', 'go'], ['saml-sso', 'typescript'], ['money', 'java'], ['webhook-verification']]) {
    const result = JSON.parse(cli('outline', ref, ...(language ? ['--language', language] : []), '--json'));
    const text = cli('outline', ref, ...(language ? ['--language', language] : []));
    add('Learn an API', `outline ${ref}${language ? ' --language ' + language : ''}`, bytes(text), 'read its source files', result.sourceBytes);
  }
  add('Load the skill', 'skills/genlib-use/SKILL.md', bytes(readFileSync(root + 'skills/genlib-use/SKILL.md', 'utf8')), '-', null);
  add('Register MCP tools', 'tools/list', bytes(JSON.stringify(JSON.parse(mcp({ method: 'tools/list' })).result)), '-', null);
  add('Decision packet', 'jev add passkey login to a Go API', bytes(cli('jev', 'add', 'passkey', 'login', 'to', 'a', 'Go', 'API', '--json')), '-', null);
  return rows;
}

const tokens = value => '~' + Math.round(value / 4).toLocaleString('en-US');
export function render(rows) {
  const lines = [
    '# Token budget',
    '',
    'Generated by `npm run tokens:report` from this checkout; `npm run tokens:check` (part of `npm run check`) fails when it is stale. Bytes are measured from the real command output an agent reads. Tokens are an estimate at 4 bytes per token; real counts depend on the model\'s tokenizer.',
    '',
    'The baseline column is what the same step costs without the compact path: the full JSON records, or reading the source files. It is not a claim about a whole task; measure end-to-end cost per accepted change for that.',
    '',
    '| Step | Command | Bytes | Tokens (est.) | Baseline | Baseline bytes | Ratio |',
    '| --- | --- | ---: | ---: | --- | ---: | ---: |',
  ];
  for (const row of rows) {
    const ratio = row.baseline ? (row.baseline / row.genlib).toFixed(1) + '×' : '-';
    lines.push(`| ${row.path} | \`${row.command}\` | ${row.genlib.toLocaleString('en-US')} | ${tokens(row.genlib)} | ${row.baselineLabel} | ${row.baseline ? row.baseline.toLocaleString('en-US') : '-'} | ${ratio} |`);
  }
  lines.push('', '## Budgets enforced by tests', '', '`tests/token-budget.test.mjs` fails when a compact path grows past its budget:', '',
    '- Representative `quick` decisions: at most 1,200 bytes in the budget tests; this is not a universal output cap.',
    '- `find` text output with 8 results: at most 2,000 bytes.',
    '- `outline`: at most half the bytes of the source it describes.',
    '- `SKILL.md`: at most 5,000 bytes.',
    '- MCP `tools/list`: at most 4,500 bytes.',
    '- Jev packet: at most 20,000 characters of state and questions (Genisys\' limit).',
    '', '## Optional reuse path', '',
    'Use the app\'s existing components and installed libraries first. A known compatible Genlib component can be reused directly; a catalog lookup is optional.',
    '',
    '1. When discovery is useful, `genlib quick <task> --target "$APP_ROOT"` returns one candidate and its install or copy commands.',
    '2. Read the install handoff or `genlib outline <id> --language <lang>` for the selected API; inspect targeted source only as integration or repair requires.',
    '3. Run the app\'s own checks. `genlib verify` checks copied hashes; it does not test application behavior.',
    '', 'Use `find` (compact text) when you need to compare options, and `--json` only when you need licenses, links or summaries.', '');
  return lines.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = render(measure());
  if (process.argv.includes('--check')) {
    const current = readFileSync(root + FILE, 'utf8');
    if (current !== text) { process.stdout.write(`${FILE} is stale. Run npm run tokens:report.\n`); process.exit(1); }
    process.stdout.write(`${FILE} is current.\n`);
  } else {
    writeFileSync(root + FILE, text);
    process.stdout.write(`Wrote ${FILE}.\n`);
  }
}
