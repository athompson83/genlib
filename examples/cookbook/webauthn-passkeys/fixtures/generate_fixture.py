"""Regenerate passkey-es256-none.json: a recorded software-authenticator ceremony.

The fixture lets every language's test call the real WebAuthn library's
verify functions without a hardware authenticator. It contains a "none"
attestation registration and one assertion signed by a throwaway P-256 key.
The private key is discarded; only public data is written.

    python3 -I generate_fixture.py > passkey-es256-none.json

Requires: cryptography, cbor2 (both are py_webauthn dependencies).
"""
import base64
import hashlib
import json
import os
import struct

import cbor2
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import ec

RP_ID = "example.com"
ORIGIN = "https://example.com"


def b64url(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


def client_data(kind: str, challenge: bytes) -> bytes:
    return json.dumps(
        {"type": kind, "challenge": b64url(challenge), "origin": ORIGIN, "crossOrigin": False},
        separators=(",", ":"),
    ).encode()


def main() -> None:
    key = ec.generate_private_key(ec.SECP256R1())
    nums = key.public_key().public_numbers()
    cose_key = cbor2.dumps(
        {1: 2, 3: -7, -1: 1, -2: nums.x.to_bytes(32, "big"), -3: nums.y.to_bytes(32, "big")}
    )
    rp_hash = hashlib.sha256(RP_ID.encode()).digest()
    cred_id = os.urandom(16)
    user_id = os.urandom(16)
    reg_challenge = os.urandom(32)
    auth_challenge = os.urandom(32)

    # UP | UV | BE | BS | AT ; sign count 0 ; zero AAGUID (no attestation)
    reg_auth_data = (
        rp_hash + bytes([0x5D]) + struct.pack(">I", 0) + bytes(16)
        + struct.pack(">H", len(cred_id)) + cred_id + cose_key
    )
    att_obj = cbor2.dumps({"fmt": "none", "attStmt": {}, "authData": reg_auth_data})
    reg_cdj = client_data("webauthn.create", reg_challenge)

    # UP | UV | BE | BS ; sign count 1
    asr_auth_data = rp_hash + bytes([0x1D]) + struct.pack(">I", 1)
    asr_cdj = client_data("webauthn.get", auth_challenge)
    signature = key.sign(asr_auth_data + hashlib.sha256(asr_cdj).digest(), ec.ECDSA(hashes.SHA256()))

    print(json.dumps({
        "comment": "Software-authenticator fixture generated by generate_fixture.py. Test data only.",
        "rpId": RP_ID,
        "origin": ORIGIN,
        "userId": b64url(user_id),
        "userName": "alice@example.com",
        "credentialId": b64url(cred_id),
        "credentialPublicKeyCose": b64url(cose_key),
        "registrationChallenge": b64url(reg_challenge),
        "registrationResponse": {
            "id": b64url(cred_id), "rawId": b64url(cred_id), "type": "public-key",
            "response": {
                "clientDataJSON": b64url(reg_cdj),
                "attestationObject": b64url(att_obj),
                "transports": ["internal", "hybrid"],
            },
            "clientExtensionResults": {}, "authenticatorAttachment": "platform",
        },
        "authenticationChallenge": b64url(auth_challenge),
        "authenticationResponse": {
            "id": b64url(cred_id), "rawId": b64url(cred_id), "type": "public-key",
            "response": {
                "clientDataJSON": b64url(asr_cdj),
                "authenticatorData": b64url(asr_auth_data),
                "signature": b64url(signature),
                "userHandle": b64url(user_id),
            },
            "clientExtensionResults": {}, "authenticatorAttachment": "platform",
        },
        "expectedSignCountAfterAuthentication": 1,
    }, indent=2))


if __name__ == "__main__":
    main()
