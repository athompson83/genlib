func TestInvalid(t *testing.T) {
	for _, rule := range []string{"FREQ=HOURLY", "COUNT=3", "FREQ=DAILY;COUNT=2;UNTIL=20261231T000000Z", "FREQ=WEEKLY;BYDAY=1MO", "FREQ=DAILY;BYDAY=1MO", "FREQ=MONTHLY;BYMONTHDAY=32", "FREQ=MONTHLY;BYMONTHDAY=0", "FREQ=MONTHLY;BYSETPOS=1", "FREQ=WEEKLY;WKST=MO", "FREQ=WEEKLY;INTERVAL=0", "FREQ=WEEKLY;INTERVAL=-1", "FREQ=MONTHLY;BYDAY=6MO", "FREQ=YEARLY;BYMONTH=1;BYDAY=6MO", "FREQ=YEARLY;BYDAY=54MO", "FREQ=MONTHLY;BYDAY=0MO", "FREQ=MONTHLY;BYDAY=MO,1TU", "FREQ=YEARLY;BYMONTH=13", "FREQ=YEARLY;BYMONTH=-1", "FREQ=YEARLY;UNTIL=2026-12-31", "FREQ=DAILY;FREQ=DAILY", "FREQ=WEEKLY;BYDAY=XX", "FREQ=DAILY;BYHOUR=9",
		"", "FREQ=WEEKLY;COUNT=-3", "FREQ=MONTHLY;BYDAY=1MO,MO", "FREQ=MONTHLY;BYDAY=001MO"} {
		if got, err := Expand("2026-01-01T00:00:00Z", rule, DefaultLimit); err == nil {
			t.Errorf("Expand(%q) = %v, want error", rule, got)
		}
	}
	for _, start := range []string{"2026-01-01 00:00:00Z", "2026-02-30T00:00:00Z", "2026-01-01T24:00:00Z", "2026-01-01T00:00:00"} {
		if _, err := Expand(start, "FREQ=DAILY", 1); err == nil {
			t.Errorf("dtstart %q accepted", start)
		}
	}
	for _, limit := range []int{0, 1001} {
		if _, err := Expand("2026-01-01T00:00:00Z", "FREQ=DAILY", limit); err == nil {
			t.Errorf("limit %d accepted", limit)
		}
	}
}

func TestWidened(t *testing.T) {
	for _, rule := range []string{"FREQ=DAILY;BYDAY=MO", "FREQ=MONTHLY;BYDAY=MO;BYMONTHDAY=1", "FREQ=YEARLY;BYDAY=20MO"} {
		if _, err := Expand("2026-01-01T00:00:00Z", rule, DefaultLimit); err != nil {
			t.Errorf("Expand(%q) = %v, want success", rule, err)
		}
	}
	if got, err := Expand("2026-01-01T00:00:00Z", "FREQ=DAILY;BYMONTH=2;BYMONTHDAY=30;COUNT=1", DefaultLimit); err != nil || len(got) != 0 {
		t.Errorf("impossible rule gave %v, %v", got, err)
	}
}

func TestLimits(t *testing.T) {
	if got, _ := Expand("2026-01-01T00:00:00Z", "FREQ=DAILY", 3); len(got) != 3 {
		t.Errorf("limit 3 gave %d", len(got))
	}
	if got, _ := Expand("2026-01-01T00:00:00Z", "FREQ=DAILY", DefaultLimit); len(got) != DefaultLimit {
		t.Errorf("default limit gave %d", len(got))
	}
	if got, err := Expand("2026-02-29T00:00:00Z", "FREQ=YEARLY", 5); err == nil {
		t.Errorf("invalid date accepted: %v", got)
	}
	if got, _ := Expand("2026-01-01T00:00:00Z", "FREQ=DAILY;UNTIL=20251231T000000Z", 5); len(got) != 0 {
		t.Errorf("UNTIL before dtstart gave %v", got)
	}
	if got, _ := Expand("9999-12-30T00:00:00Z", "FREQ=DAILY", 5); len(got) != 2 {
		t.Errorf("year 9999 bound gave %v", got)
	}
}
