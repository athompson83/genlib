fun main() {
    CASES.forEachIndexed { k, v -> eq(v[3], Slugify.slugify(v[0], v[1], v[2].toInt()), "case $k") }
    INVALID.forEachIndexed { k, v -> throwsIae("invalid $k") { Slugify.slugify(v[0], v[1], v[2].toInt()) } }
    UNIQUE.forEachIndexed { k, v -> eq(v[1], Slugify.uniqueSlug(v[0], v.drop(2).toSet()), "unique $k") }
    throwsIae("empty base") { Slugify.uniqueSlug("", emptySet()) }
    eq("post_2", Slugify.uniqueSlug("post", setOf("post"), "_"), "unique with separator")
    eq(190, TABLE.size, "table size")
    for (t in TABLE) eq(t[1].lowercase(), Slugify.slugify(t[0]), "table U+${t[0][0].code.toString(16)}")
    eq("hello-world", Slugify.slugify("Hello, World!"), "default separator")
    eq("hello_world", Slugify.slugify("Hello, World!", "_"), "two-argument form")

    println("SlugifyTest: $passed passed, $failed failed")
    if (failed > 0) exitProcess(1)
}
