async function make(tenantId: string, input: Record<string, unknown>): Promise<string> {
  const r: any = await createEvent(tenantId, { title: 'Event', durationMinutes: 30, ...input } as any)
  assert.equal(r.ok, true, `createEvent failed: ${JSON.stringify(r)} for ${JSON.stringify(input)}`)
  return r.event.id
}
async function list(tenantId: string, window: { from: string; to: string; limit?: number } = ALL) {
  const r: any = await listOccurrences(tenantId, window)
  assert.equal(r.ok, true, `listOccurrences failed: ${JSON.stringify(r)}`)
  return r as { ok: true; truncated: boolean; occurrences: { eventId: string; title: string; originalStart: string; localStart: string; start: string; end: string }[] }
}
const rows = (occ: { originalStart: string; localStart: string; start: string }[]): Row[] => occ.map(o => [o.originalStart, o.localStart, o.start])
async function caseEvent(name: string, extra: Record<string, unknown> = {}): Promise<string> {
  const [timeZone, start, rrule] = CASES[name]!
  return make('acme', { title: name, timeZone, start, rrule, ...extra })
}
async function checkCases(...names: string[]) {
  const ids = new Map<string, string>()
  for (const name of names) ids.set(name, await caseEvent(name))
  const { occurrences } = await list('acme')
  for (const name of names) {
    assert.deepEqual(rows(occurrences.filter(o => o.eventId === ids.get(name))), EXPECTED[name], name)
  }
}

