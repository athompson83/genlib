test('invalid-rules: malformed or unsupported RRULEs and other bad inputs are refused with exact codes', async () => {
  const bad = [
    '', 'FREQ=HOURLY', 'FREQ=SECONDLY', 'FREQ=FORTNIGHTLY', 'INTERVAL=2', 'COUNT=3', 'FREQ=DAILY;FREQ=WEEKLY', 'FREQ=DAILY;COUNT=0', 'FREQ=DAILY;COUNT=-1',
    'FREQ=DAILY;COUNT=1.5', 'FREQ=DAILY;COUNT=3;UNTIL=20270101T000000Z', 'FREQ=DAILY;INTERVAL=0', 'FREQ=DAILY;INTERVAL=', 'FREQ=DAILY;', 'FREQ=DAILY;;COUNT=2',
    'FREQ=WEEKLY;BYDAY=XX', 'FREQ=WEEKLY;BYDAY=MO,,TU', 'FREQ=WEEKLY;BYDAY=2TU', 'FREQ=DAILY;BYDAY=-1FR', 'FREQ=MONTHLY;BYDAY=6MO', 'FREQ=MONTHLY;BYDAY=0MO',
    'FREQ=YEARLY;BYDAY=54MO', 'FREQ=MONTHLY;BYDAY=+MO', 'FREQ=MONTHLY;BYMONTHDAY=0', 'FREQ=MONTHLY;BYMONTHDAY=32', 'FREQ=MONTHLY;BYMONTHDAY=-32', 'FREQ=WEEKLY;BYMONTHDAY=1',
    'FREQ=YEARLY;BYMONTH=13', 'FREQ=YEARLY;BYMONTH=0', 'FREQ=MONTHLY;BYSETPOS=1', 'FREQ=MONTHLY;BYDAY=MO;BYSETPOS=0', 'FREQ=MONTHLY;BYDAY=MO;BYSETPOS=367',
    'FREQ=WEEKLY;WKST=XY', 'FREQ=DAILY;BYHOUR=9', 'FREQ=YEARLY;BYWEEKNO=1', 'FREQ=DAILY;X-NAME=1', 'FREQ=DAILY;UNTIL=20270101', 'FREQ=DAILY;UNTIL=2027-01-01T00:00:00Z',
    'FREQ=DAILY;UNTIL=20270230T000000Z', 'FREQ', 'FREQ=DAILY;COUNT',
  ]
  for (const rule of bad) assert.deepEqual(await validateRule(rule), { ok: false, error: 'invalid_rrule' }, JSON.stringify(rule))
  const good = [
    'FREQ=DAILY', 'RRULE:FREQ=WEEKLY;BYDAY=MO,WE', 'freq=monthly;byday=-1fr', 'FREQ=YEARLY;BYMONTH=11;BYDAY=4TH', 'FREQ=YEARLY;BYDAY=20MO',
    'FREQ=MONTHLY;BYMONTHDAY=+5,-1', 'FREQ=MONTHLY;BYDAY=MO;BYSETPOS=-366', 'FREQ=WEEKLY;INTERVAL=2;WKST=SU;BYDAY=TU,SU', 'FREQ=DAILY;UNTIL=20270101T000000',
    'FREQ=YEARLY;BYMONTH=6;BYSETPOS=1',
  ]
  for (const rule of good) assert.deepEqual(await validateRule(rule), { ok: true }, rule)

  const base = { title: 'Weekly', timeZone: NY, start: '2026-03-02T09:00:00', durationMinutes: 30, rrule: 'FREQ=WEEKLY' }
  const cases: [Record<string, unknown>, string][] = [
    [{ rrule: 'FREQ=WEEKLY;BYDAY=2TU' }, 'invalid_rrule'], [{ rrule: 'FREQ=DAILY;UNTIL=20260302T135959Z' }, 'invalid_rrule'],
    [{ rrule: 'FREQ=DAILY;UNTIL=20260302T085959' }, 'invalid_rrule'], [{ rrule: 42 }, 'invalid_rrule'],
    [{ title: '' }, 'invalid_title'], [{ title: '   ' }, 'invalid_title'], [{ title: 'x'.repeat(201) }, 'invalid_title'], [{ title: 7 }, 'invalid_title'],
    [{ timeZone: 'Mars/Olympus_Mons' }, 'invalid_time_zone'], [{ timeZone: '' }, 'invalid_time_zone'], [{ timeZone: undefined }, 'invalid_time_zone'],
    [{ start: '2026-02-30T09:00:00' }, 'invalid_start'], [{ start: '2026-03-02T09:00' }, 'invalid_start'], [{ start: '2026-03-02 09:00:00' }, 'invalid_start'],
    [{ start: '2026-03-02T24:00:00' }, 'invalid_start'], [{ start: '2026-03-02T09:00:00Z' }, 'invalid_start'], [{ start: '1969-12-31T09:00:00' }, 'invalid_start'],
    [{ durationMinutes: 0 }, 'invalid_duration'], [{ durationMinutes: 1.5 }, 'invalid_duration'], [{ durationMinutes: 10081 }, 'invalid_duration'], [{ durationMinutes: '30' }, 'invalid_duration'],
    [{ exdates: ['2026-03-09'] }, 'invalid_date'], [{ rdates: '2026-03-10T09:00:00' }, 'invalid_date'], [{ rdates: ['2026-03-10T09:00:00', 'soon'] }, 'invalid_date'],
    [{ title: '', timeZone: 'Nowhere/Here', rrule: 'FREQ=NEVER' }, 'invalid_title'], [{ start: 'bad', rrule: 'FREQ=NEVER' }, 'invalid_start'],
  ]
  for (const [patch, error] of cases) {
    assert.deepEqual(await createEvent('acme', { ...base, ...patch } as any), { ok: false, error }, JSON.stringify(patch))
  }
  assert.deepEqual((await list('acme')).occurrences, [], 'refused events store nothing')
  const okRule: any = await createEvent('acme', { ...base, rrule: 'FREQ=DAILY;UNTIL=20260302T140000Z' })
  assert.equal(okRule.ok, true, 'UNTIL equal to the start instant is allowed')
  assert.equal((await list('acme')).occurrences.length, 1)
})
